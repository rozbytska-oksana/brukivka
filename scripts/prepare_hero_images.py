"""Export the small responsive size used by the decorative stone grid.

Run with Python + Pillow. Originals are read-only; no AI editing or recoloring.
"""
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'public/images/hero'
OUTPUT.mkdir(parents=True, exist_ok=True)
stones = []
original_bytes = 0
preview_bytes = {400: 0}
for number in (1, 2, 3, 4, 6, 7, 11, 15):
    source = ROOT / f'public/images/kamen1/1_{number}.jpg'
    original_bytes += source.stat().st_size
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        profile = original.info.get('icc_profile')
        variants = []
        for maximum in preview_bytes:
            preview = image.copy()
            preview.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
            filename = f'stone-{number}-{preview.width}.webp'
            preview.save(
                OUTPUT / filename, 'WEBP', quality=90, method=6,
                **({'icc_profile': profile} if profile else {}),
            )
            preview_bytes[maximum] += (OUTPUT / filename).stat().st_size
            variants.append({'src': f'images/hero/{filename}', 'width': preview.width})
        variants.append({'src': f'images/kamen1/1_{number}.jpg', 'width': image.width})
        stones.append({
            'id': str(number),
            'src': variants[0]['src'],
            'width': image.width,
            'height': image.height,
            'variants': variants,
        })

(ROOT / 'app/data/hero-images.ts').write_text(
    '// Generated by scripts/prepare_hero_images.py; originals remain unchanged.\n'
    + 'export const heroImages = ' + json.dumps(stones, indent=2) + ';\n',
    encoding='utf-8',
)
print(json.dumps({'original_bytes': original_bytes, 'preview_bytes': preview_bytes}))
